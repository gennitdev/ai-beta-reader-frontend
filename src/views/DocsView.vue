            :key="screenshot.src"
            class="group flex min-w-0 flex-col overflow-hidden rounded-2xl border border-slate-200 bg-white shadow-[0_18px_50px_-28px_rgba(15,23,42,0.45)] dark:border-white/10 dark:bg-navy-900 dark:shadow-black/30"
