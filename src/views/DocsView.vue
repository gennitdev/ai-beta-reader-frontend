              :class="[
                'flex h-5 w-5 items-center justify-center rounded-full text-[11px] font-bold',
                currentSectionIndex === index
                  ? 'bg-white/15 dark:bg-navy-900/15'
                  : 'bg-white text-slate-500 shadow-sm dark:bg-white/10 dark:text-slate-300'
              ]"
            >
              {{ index + 1 }}
            </span>
            {{ section.title }}
          </button>
        </div>
      </div>
    </nav>

